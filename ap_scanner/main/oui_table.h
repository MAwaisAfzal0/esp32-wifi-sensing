static const int OUI_TABLE_LEN = sizeof(OUI_TABLE) / sizeof(OUI_TABLE[0]);

/* Best-effort vendor for a globally administered MAC. NULL when the prefix
 * is not in the table (or the address is randomised, which the caller checks). */
static inline const char *oui_lookup(const uint8_t *mac)
{
    uint32_t key = ((uint32_t)mac[0] << 16) | ((uint32_t)mac[1] << 8) | mac[2];
    int lo = 0, hi = OUI_TABLE_LEN - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (OUI_TABLE[mid].prefix == key) return OUI_LABELS[OUI_TABLE[mid].label];
        if (OUI_TABLE[mid].prefix < key) lo = mid + 1; else hi = mid - 1;
    }
    return NULL;
}
